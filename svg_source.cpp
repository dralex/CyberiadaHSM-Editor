#include "svg_source.h"

#include <QCryptographicHash>
#include <QDir>
#include <QFile>
#include <QFileInfo>
#include <QXmlStreamReader>

const char* const SVG_SOURCE_NAMESPACE = "https://cyberiada.dev/ns/svg#";
static const char* const RDF_NAMESPACE = "http://www.w3.org/1999/02/22-rdf-syntax-ns#";
static const char* const DC_NAMESPACE = "http://purl.org/dc/elements/1.1/";
static const char* const DIGEST_PREFIX = "sha256:";

QString fileDigest(const QString& path)
{
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly)) return QString();
    QCryptographicHash hash(QCryptographicHash::Sha256);
    if (!hash.addData(&file)) return QString();
    return DIGEST_PREFIX + QString::fromLatin1(hash.result().toHex());
}

// the text of the first <name> element replaced, the element added after the root without one
static void setElementText(QString& svg, const QString& name, const QString& value)
{
    QString open = "<" + name + ">";
    QString close = "</" + name + ">";
    int start = svg.indexOf(open);
    int end = start < 0 ? -1 : svg.indexOf(close, start);
    if (end >= 0) {
        svg.replace(start + open.size(), end - start - open.size(), value);
        return;
    }
    int root = svg.indexOf("<svg");
    int after = root < 0 ? -1 : svg.indexOf('>', root);
    if (after >= 0) svg.insert(after + 1, "\n" + open + value + close);
}

QByteArray recordSvgSource(const QByteArray& svg, const QString& svgPath, const QString& graphml,
                           const QString& title, const QString& font)
{
    QString text = QString::fromUtf8(svg);
    QString name = QFileInfo(graphml).fileName();
    setElementText(text, "title", title.toHtmlEscaped());
    setElementText(text, "desc", QString("Generated by CyberiadaPro from %1").arg(name).toHtmlEscaped());
    int root = text.indexOf("<svg");
    int rootEnd = root < 0 ? -1 : text.indexOf('>', root);
    if (rootEnd < 0) return svg;
    text.insert(rootEnd, QString(" xmlns:rdf=\"%1\" xmlns:dc=\"%2\" xmlns:cyb=\"%3\"")
                         .arg(RDF_NAMESPACE, DC_NAMESPACE, SVG_SOURCE_NAMESPACE));
    QString source = QDir(QFileInfo(svgPath).absolutePath())
                         .relativeFilePath(QFileInfo(graphml).absoluteFilePath());
    QString block = QString("<metadata>\n<rdf:RDF>\n<rdf:Description rdf:about=\"\">\n"
                            "<dc:source>%1</dc:source>\n<dc:format>image/svg+xml</dc:format>\n"
                            "<cyb:sourceDigest>%2</cyb:sourceDigest>\n<cyb:font>%3</cyb:font>\n"
                            "</rdf:Description>\n</rdf:RDF>\n</metadata>\n")
                        .arg(source.toHtmlEscaped(), fileDigest(graphml), font.toHtmlEscaped());
    // after the description, else first in the root
    const QString descEnd = "</desc>";
    int desc = text.indexOf(descEnd);
    int at = desc >= 0 ? desc + descEnd.size() : text.indexOf('>', root) + 1;
    if (at < text.size() && text.at(at) == '\n') at++;
    else block.prepend('\n');
    text.insert(at, block);
    return text.toUtf8();
}

SvgSource readSvgSource(const QString& svgPath)
{
    SvgSource result;
    QFile file(svgPath);
    if (!file.open(QIODevice::ReadOnly)) return result;
    QString source, recordedFont, drawnFont;
    QXmlStreamReader xml(&file);
    while (!xml.atEnd()) {
        if (xml.readNext() != QXmlStreamReader::StartElement) continue;
        if (drawnFont.isEmpty() && xml.attributes().hasAttribute("font-family")) {
            drawnFont = xml.attributes().value("font-family").toString();
        }
        if (xml.namespaceUri() == QLatin1String(DC_NAMESPACE) && xml.name() == QLatin1String("source")) {
            source = xml.readElementText().trimmed();
        } else if (xml.namespaceUri() == QLatin1String(SVG_SOURCE_NAMESPACE)) {
            if (xml.name() == QLatin1String("sourceDigest")) result.digest = xml.readElementText().trimmed();
            else if (xml.name() == QLatin1String("font")) recordedFont = xml.readElementText().trimmed();
        }
    }
    result.font = recordedFont.isEmpty() ? drawnFont : recordedFont;
    if (!source.isEmpty()) {
        result.graphml = QDir::cleanPath(QFileInfo(svgPath).absoluteDir().absoluteFilePath(source));
    }
    return result;
}
